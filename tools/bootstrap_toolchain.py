#!/usr/bin/env python3
"""Set up the no-admin native toolchain in .toolchain/ (gitignored).

Creates a venv with pinned CMake, Ninja and Zig from PyPI, then writes
one-line .cmd wrappers around `zig cc`, `zig c++`, `zig ar`, `zig ranlib`
and `zig rc`, plus a CMake toolchain file pointing at them. Zig targets
x86_64-windows-gnu (Clang + mingw-w64, UCRT). See Docs/slipx-windows-build.md
for why this is used instead of MSVC for now.

Usage (from the repo root):
    python tools/bootstrap_toolchain.py
    .toolchain/venv/Scripts/cmake -S . -B build -G Ninja \
        -DCMAKE_TOOLCHAIN_FILE=.toolchain/zig-toolchain.cmake
"""

from __future__ import annotations

import subprocess
import sys
import venv
from pathlib import Path

PINS = ["cmake==4.4.4", "ninja==1.13.2", "ziglang==0.16.0"]

ROOT = Path(__file__).resolve().parent.parent
TC = ROOT / ".toolchain"
VENV = TC / "venv"


def main() -> int:
    if sys.platform != "win32":
        print("This bootstrap is for Windows; elsewhere use the system compiler.")
        return 1

    python = VENV / "Scripts" / "python.exe"
    if not python.exists():
        venv.create(VENV, with_pip=True)
    subprocess.check_call([str(python), "-m", "pip", "install", "--quiet", *PINS])

    zig = VENV / "Lib" / "site-packages" / "ziglang" / "zig.exe"
    if not zig.exists():
        print(f"zig not found at {zig}", file=sys.stderr)
        return 1

    tools = {"cc": "cc", "c++": "c++", "ar": "ar", "ranlib": "ranlib", "rc": "rc"}
    for name, sub in tools.items():
        (TC / f"zig-{name}.cmd").write_text(
            f'@echo off\r\n"{zig}" {sub} %*\r\n', encoding="ascii"
        )

    def p(name: str) -> str:
        return (TC / f"zig-{name}.cmd").as_posix()

    (TC / "zig-toolchain.cmake").write_text(
        "# Generated by tools/bootstrap_toolchain.py. Do not edit.\n"
        f'set(CMAKE_C_COMPILER   "{p("cc")}")\n'
        f'set(CMAKE_CXX_COMPILER "{p("c++")}")\n'
        f'set(CMAKE_AR           "{p("ar")}" CACHE FILEPATH "")\n'
        f'set(CMAKE_RANLIB       "{p("ranlib")}" CACHE FILEPATH "")\n'
        f'set(CMAKE_RC_COMPILER  "{p("rc")}" CACHE FILEPATH "")\n'
        f'set(CMAKE_MAKE_PROGRAM "{(VENV / "Scripts" / "ninja.exe").as_posix()}" CACHE FILEPATH "")\n',
        encoding="utf-8",
    )
    print(f"Toolchain ready in {TC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
