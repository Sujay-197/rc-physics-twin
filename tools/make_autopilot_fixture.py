#!/usr/bin/env python3
"""Write the fixture that keeps the Unity autopilot honest to Python.

The Unity twin drives with C# ports of the RL environment's observation
(sim_py/rc_twin_env.py) and of the tuned pure pursuit (sim_py/controllers.py),
on campus routes found by a port of sim_py/campus.py. This records what
Python computes, and Unity's Edit Mode tests (AutopilotParityTests.cs)
recompute it from the same states:

  episodes  the tuned pure pursuit driving AB2 -> S3 on the nominal car, in
            each task ("follow": from the target speed; "stop": from rest to
            a stop): per control tick the Core state, where the car is along
            the route (s, d), the frame, the full observation (history 4) and
            the action. The stop episode is recorded every tick up to the
            stop, so it covers the braking
  routes    the route centreline for a spread of stop pairs

and two small policies in tools/export_policy.py's format, for the C#
PolicyDriver: random weights (seeded), so they need no training and no
torch, with the actions this script computes for them on the episodes'
observations ("checks"):

  policy_residual_stop.json   residual on the tuned pure pursuit, "stop" task,
                              tanh head (as SAC)
  policy_follow.json          plain, "follow" task, clipped head (as PPO)

tools/test_autopilot_fixture.py (ctest tools.autopilot_fixture) fails when
the committed fixture no longer matches what Python computes, so a change to
the environment or the controller shows up as a parity question.

    python tools/make_autopilot_fixture.py
"""

from __future__ import annotations

import json
import math
import os
import random
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "sim_py"))
FIXTURES = ROOT / "unity" / "RcTwin" / "Assets" / "RcTwin" / "Tests" / "Editor" / "Fixtures"
FIXTURE = FIXTURES / "autopilot_parity.json"
POLICIES = {"policy_residual_stop.json": ("stop", True, "tanh"), "policy_follow.json": ("follow", False, "clip")}
TICKS = 80
TRIP = ("AB2", "S3")       # turns 74 deg 1.5 m from the start
PAIRS = [("S3", "AB1"), ("AB1", "S3"), ("S1", "S6"), ("AB3", "S4"), ("S6", "AB2"), ("AB4", "S5"), ("S2", "AB3")]
STATE_FIELDS = ("x", "y", "z", "yaw", "pitch", "roll", "vx", "vy", "vz", "roll_rate", "pitch_rate", "yaw_rate",
                "w_fl", "w_fr", "w_rl", "w_rr", "steer", "steer_rate", "soc", "pack_v", "fz_fl", "fz_fr", "fz_rl",
                "fz_rr", "lag_fl", "lag_fr", "lag_rl", "lag_rr")


def episode(c, ev, lib: str, task: str, ticks_max: int, every: int) -> tuple[dict, object]:
    env = c.CampusEnv(seed=0, ranges=c.envmod.RANGES_NOMINAL, lib_path=lib, target_speed=4.0, history=4, task=task)
    policy = ev.build_policy("controller:pure_pursuit", env)
    obs, _ = env.reset(seed=0, options={"trip": TRIP})
    ticks, k = [], 0
    while k < ticks_max:
        st = env.state
        a = policy(obs)
        if k % every == 0 or k < TICKS:
            ticks.append({"tick": k, "state": [getattr(st, f) for f in STATE_FIELDS], "s": env.s, "d": env.d,
                          "frame": list(env._frame_now), "obs": list(obs), "action": list(a)})
        obs, r, te, tr, info = env.step(a)
        k += 1
        if te or tr:
            break
    out = {"task": task, "status": info["status"], "frame_fields": env.frame_fields, "ticks": ticks,
           "road": {"width": env.road["width"], "xyz": [[q["x"], q["y"], q["z"]] for q in env.road["centreline"]]}}
    return out, env


def make(lib: str | None = None) -> dict:
    import evaluate_policies as ev
    c = ev.campus()
    lib = lib or os.environ.get("RC_TWIN_LIB") or str(ROOT / "build" / "bin" / "rc_twin.dll")
    tuned = json.loads((ROOT / "policies" / "controllers.json").read_text(encoding="utf-8"))["pure_pursuit"]["gains"]
    follow, env = episode(c, ev, lib, "follow", TICKS, 1)
    env.close()
    # every tick of the first TICKS, then every 5th to the stop
    stop, env = episode(c, ev, lib, "stop", 3000, 5)
    p = env.params
    doc = {"note": "generated by tools/make_autopilot_fixture.py; do not edit",
           "trip": list(TRIP), "target_speed": env.target_speed, "history": env.history,
           "remaining_scale_m": c.envmod.REMAINING_SCALE_M,
           "car": {"wheel_radius": p.wheel_radius, "steer_max": p.steer_max, "lf": p.lf, "lr": p.lr},
           "pure_pursuit": tuned, "state_fields": list(STATE_FIELDS), "episodes": [follow, stop],
           "routes": [{"from": a, "to": b, "xyz": c.CampusNetwork.load().route_points(
               c.CampusNetwork.load().stops[a]["node"], c.CampusNetwork.load().stops[b]["node"])} for a, b in PAIRS]}
    env.close()
    return json.loads(json.dumps(doc))      # exactly what the file holds


def _forward(pol: dict, x: list) -> list:
    n = pol["normalise"]
    z = [max(-n["clip"], min(n["clip"], (v - m) / math.sqrt(var + n["epsilon"])))
         for v, m, var in zip(x, n["mean"], n["var"])]
    for layer in pol["layers"]:
        z = [sum(w * v for w, v in zip(row, z)) + b for row, b in zip(layer["weight"], layer["bias"])]
        z = [math.tanh(v) if layer["activation"] == "tanh" else max(0.0, v) if layer["activation"] == "relu" else v
             for v in z]
    return [math.tanh(v) for v in z] if pol["head"] == "tanh" else [max(-1.0, min(1.0, v)) for v in z]


def make_policies(doc: dict) -> dict:
    """The two synthetic policies, with checks on the matching episode."""
    out = {}
    for name, (task, residual, head) in POLICIES.items():
        ep = next(e for e in doc["episodes"] if e["task"] == task)
        rng = random.Random(name)
        n_in = len(ep["ticks"][0]["obs"]) + (2 if residual else 0)
        sizes = [n_in, 8, 2]
        layers = [{"weight": [[rng.gauss(0.0, 1.0 / math.sqrt(a)) for _ in range(a)] for _ in range(b)],
                   "bias": [rng.gauss(0.0, 0.1) for _ in range(b)],
                   "activation": "tanh" if k < len(sizes) - 2 else "linear"}
                  for k, (a, b) in enumerate(zip(sizes[:-1], sizes[1:]))]
        pol = {"format": "rc-physics-twin policy 0.1.0", "name": name.removesuffix(".json"),
               "algo": "sac" if head == "tanh" else "ppo", "selected": None, "task": task,
               "target_speed": doc["target_speed"], "history": doc["history"],
               "residual": ({"kind": "pure_pursuit", "scale": 0.5, "gains": doc["pure_pursuit"]} if residual else None),
               "normalise": {"mean": [rng.gauss(0.0, 0.3) for _ in range(n_in)],
                             "var": [rng.uniform(0.2, 2.0) for _ in range(n_in)], "epsilon": 1e-8, "clip": 10.0},
               "layers": layers, "head": head, "note": "synthetic: tools/make_autopilot_fixture.py"}
        checks = []
        for t in ep["ticks"][:40]:
            x = list(t["obs"]) + (list(t["action"]) if residual else [])   # the tuned pure pursuit is the base
            a = _forward(pol, x)
            if residual:
                a = [max(-1.0, min(1.0, b + 0.5 * v)) for b, v in zip(t["action"], a)]
            checks.append({"obs": t["obs"], "action": a})
        pol["checks"] = checks
        out[name] = json.loads(json.dumps(pol))
    return out


def main() -> int:
    doc = make()
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(doc, separators=(",", ":")) + "\n", encoding="utf-8")
    for name, pol in make_policies(doc).items():
        (FIXTURES / name).write_text(json.dumps(pol, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"wrote {FIXTURE}: " + ", ".join(f"{e['task']} {len(e['ticks'])} ticks ({e['status']})" for e in doc['episodes'])
          + f", {len(doc['routes'])} routes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
