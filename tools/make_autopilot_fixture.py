#!/usr/bin/env python3
"""Write the fixture that keeps the Unity autopilot honest to Python.

The Unity twin drives with C# ports of the RL environment's observation
(sim_py/rc_twin_env.py) and of the tuned pure pursuit (sim_py/controllers.py),
on campus routes found by a port of sim_py/campus.py. This records what
Python computes, and Unity's Edit Mode tests (AutopilotParityTests.cs)
recompute it from the same states:

  episode   the tuned pure pursuit driving AB2 -> S3 on the nominal car: per
            control tick the Core state, where the car is along the route
            (s, d), the frame, the full observation (history 4) and the action
  routes    the route centreline for a spread of stop pairs

tools/test_autopilot_fixture.py (ctest tools.autopilot_fixture) fails when
the committed fixture no longer matches what Python computes, so a change to
the environment or the controller shows up as a parity question.

    python tools/make_autopilot_fixture.py
"""

from __future__ import annotations

import json
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "sim_py"))
FIXTURE = ROOT / "unity" / "RcTwin" / "Assets" / "RcTwin" / "Tests" / "Editor" / "Fixtures" / "autopilot_parity.json"
TICKS = 80
TRIP = ("AB2", "S3")       # turns 74 deg 1.5 m from the start
PAIRS = [("S3", "AB1"), ("AB1", "S3"), ("S1", "S6"), ("AB3", "S4"), ("S6", "AB2"), ("AB4", "S5"), ("S2", "AB3")]
STATE_FIELDS = ("x", "y", "z", "yaw", "pitch", "roll", "vx", "vy", "vz", "roll_rate", "pitch_rate", "yaw_rate",
                "w_fl", "w_fr", "w_rl", "w_rr", "steer", "steer_rate", "soc", "pack_v", "fz_fl", "fz_fr", "fz_rl",
                "fz_rr", "lag_fl", "lag_fr", "lag_rl", "lag_rr")


def make(lib: str | None = None) -> dict:
    import evaluate_policies as ev
    c = ev.campus()
    lib = lib or os.environ.get("RC_TWIN_LIB") or str(ROOT / "build" / "bin" / "rc_twin.dll")
    env = c.CampusEnv(seed=0, ranges=c.envmod.RANGES_NOMINAL, lib_path=lib, target_speed=4.0, history=4)
    tuned = json.loads((ROOT / "policies" / "controllers.json").read_text(encoding="utf-8"))["pure_pursuit"]["gains"]
    policy = ev.build_policy("controller:pure_pursuit", env)
    obs, _ = env.reset(seed=0, options={"trip": TRIP})
    ticks = []
    for _ in range(TICKS):
        st = env.state
        a = policy(obs)
        ticks.append({"state": [getattr(st, f) for f in STATE_FIELDS], "s": env.s, "d": env.d,
                      "frame": list(env._frame_now), "obs": list(obs), "action": list(a)})
        obs, r, te, tr, info = env.step(a)
        if te or tr:
            break
    p = env.params
    doc = {"note": "generated by tools/make_autopilot_fixture.py; do not edit",
           "trip": list(TRIP), "target_speed": env.target_speed, "history": env.history,
           "road": {"width": env.road["width"], "xyz": [[q["x"], q["y"], q["z"]] for q in env.road["centreline"]]},
           "car": {"wheel_radius": p.wheel_radius, "steer_max": p.steer_max, "lf": p.lf, "lr": p.lr},
           "pure_pursuit": tuned, "state_fields": list(STATE_FIELDS), "ticks": ticks,
           "routes": [{"from": a, "to": b, "xyz": c.CampusNetwork.load().route_points(
               c.CampusNetwork.load().stops[a]["node"], c.CampusNetwork.load().stops[b]["node"])} for a, b in PAIRS]}
    env.close()
    return json.loads(json.dumps(doc))      # exactly what the file holds


def main() -> int:
    doc = make()
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(doc, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"wrote {FIXTURE}: {len(doc['ticks'])} ticks, {len(doc['routes'])} routes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
